BEGIN;

-- ============================================================
-- 1. TABELA CATEGORIAS
-- ============================================================

CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome TEXT NOT NULL,

    tipo_permitido TEXT NOT NULL
        CHECK (tipo_permitido IN ('receita', 'despesa')),

    CONSTRAINT categorias_nome_tipo_unico
        UNIQUE (nome, tipo_permitido)
);

-- ============================================================
-- 2. TABELA LANCAMENTOS
-- ============================================================

CREATE TABLE IF NOT EXISTS public.lancamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    descricao VARCHAR(120) NOT NULL
        CHECK (length(trim(descricao)) > 0),

    valor_centavos BIGINT NOT NULL
        CHECK (valor_centavos > 0),

    data DATE NOT NULL,

    tipo TEXT NOT NULL
        CHECK (tipo IN ('receita', 'despesa')),

    categoria_id BIGINT NOT NULL
        REFERENCES public.categorias(id)
        ON DELETE RESTRICT
);

-- ============================================================
-- 3. COLUNA AUTOMATICA: VALOR EM REAIS
-- ============================================================

ALTER TABLE public.lancamentos
ADD COLUMN IF NOT EXISTS valor_reais NUMERIC(14, 2)
GENERATED ALWAYS AS (
    valor_centavos::NUMERIC / 100
) STORED;

-- ============================================================
-- 4. INDICES PARA MELHORAR AS CONSULTAS
-- ============================================================

CREATE INDEX IF NOT EXISTS idx_lancamentos_data
ON public.lancamentos(data);

CREATE INDEX IF NOT EXISTS idx_lancamentos_categoria
ON public.lancamentos(categoria_id);

CREATE INDEX IF NOT EXISTS idx_lancamentos_tipo
ON public.lancamentos(tipo);

-- ============================================================
-- 5. CATEGORIAS INICIAIS
-- ============================================================

-- Insere categorias que ainda não existem.
-- Não apaga as categorias já cadastradas.

INSERT INTO public.categorias (nome, tipo_permitido)

SELECT origem.nome, origem.tipo_permitido

FROM (
    VALUES
        ('Salário', 'receita'),
        ('Renda Extra', 'receita'),
        ('Reembolso', 'receita'),
        ('Alimentação', 'despesa'),
        ('Moradia', 'despesa'),
        ('Transporte', 'despesa'),
        ('Saúde', 'despesa'),
        ('Educação', 'despesa'),
        ('Lazer', 'despesa'),
        ('Outros Gastos', 'despesa')
) AS origem(nome, tipo_permitido)

WHERE NOT EXISTS (
    SELECT 1
    FROM public.categorias AS existente

    WHERE existente.nome = origem.nome
      AND existente.tipo_permitido = origem.tipo_permitido
)

ON CONFLICT DO NOTHING;

COMMIT;

-- ============================================================
-- 6. CONSULTA PARA VERIFICAR AS CATEGORIAS
-- ============================================================

SELECT
    id,
    nome,
    tipo_permitido

FROM public.categorias

ORDER BY id;

-- ============================================================
-- 7. CONSULTA PARA VERIFICAR OS LANCAMENTOS
-- ============================================================

SELECT
    l.id,
    l.descricao,
    l.valor_centavos,
    l.valor_reais,
    l.data,
    l.tipo,
    c.nome AS categoria,
    l.categoria_id

FROM public.lancamentos AS l

JOIN public.categorias AS c
    ON c.id = l.categoria_id

ORDER BY l.data DESC, l.id DESC;
